#!/usr/bin/env python3
# Generates src/platform/posix/math/X87KernelsTables.h: the constants of the x87 transcendental
# kernels (X87Kernels.cpp). Python 3 stdlib only (decimal at 120 digits, fractions for exact
# rounding). Run: python3 -I macos/tests/x87-kernels/gen_tables.py [output path]
#
# Fixed-point format "Q2.125": a signed 128-bit integer v stands for v * 2^-125. Every Q2.125
# entry below is the exact value rounded to nearest (error <= 0.5 * 2^-125).
# Slow-path constants: 256-bit significands W (top bit set) with value W * 2^(e - 255), rounded
# to nearest.

import os
import sys
from decimal import Decimal, getcontext, localcontext
from fractions import Fraction
from math import factorial

PREC = 120
getcontext().prec = PREC

# Known digits of pi (check only).
PI_REF = Decimal("3.14159265358979323846264338327950288419716939937510582097494459230781640628"
                 "62089986280348253421170679821480865132823066470938446095505822317253594081284811")


def d_pi():
    # decimal docs recipe
    with localcontext() as c:
        c.prec = PREC + 5
        three = Decimal(3)
        lasts, t, s, n, na, d, da = 0, three, 3, 1, 0, 0, 24
        while s != lasts:
            lasts = s
            n, na = n + na, na + 8
            d, da = d + da, da + 32
            t = (t * n) / d
            s += t
    return +s


def d_sin(x):
    with localcontext() as c:
        c.prec = PREC + 5
        i, lasts, s, fact, num, sign = 1, 0, x, 1, x, 1
        while s != lasts:
            lasts = s
            i += 2
            fact *= i * (i - 1)
            num *= x * x
            sign *= -1
            s += num / fact * sign
    return +s


def d_cos(x):
    with localcontext() as c:
        c.prec = PREC + 5
        i, lasts, s, fact, num, sign = 0, 0, 1, 1, 1, 1
        while s != lasts:
            lasts = s
            i += 2
            fact *= i * (i - 1)
            num *= x * x
            sign *= -1
            s += num / fact * sign
    return +s


def d_atan(x):
    # atan for 0 <= x <= 1: three argument halvings, then the Taylor series.
    with localcontext() as c:
        c.prec = PREC + 8
        t = Decimal(x)
        for _ in range(3):
            t = t / (1 + (1 + t * t).sqrt())
        s, term, k, t2, lasts = t, t, 1, t * t, None
        while s != lasts:
            lasts = s
            term = -term * t2
            k += 2
            s += term / k
        s *= 8
    return +s


PI = d_pi()
assert abs(PI - PI_REF) < Decimal(10) ** -105, "pi recipe"
LN2 = Decimal(2).ln()
LOG2E = 1 / LN2

# Self-checks of the series implementations.
for a in [Decimal(1) / 3, Decimal("0.78"), Decimal(50) / 64]:
    assert abs(d_sin(a) ** 2 + d_cos(a) ** 2 - 1) < Decimal(10) ** -110
    assert abs(d_sin(2 * a) - 2 * d_sin(a) * d_cos(a)) < Decimal(10) ** -110
for a in [Decimal(1) / 64, Decimal("0.3"), Decimal(1)]:
    th = d_atan(a)
    assert abs(d_sin(th) / d_cos(th) - a) < Decimal(10) ** -110
assert abs(d_atan(Decimal(1)) * 4 - PI) < Decimal(10) ** -110


def q125(v):
    """Round a Decimal to Q2.125 (nearest, ties even), return int."""
    f = Fraction(v) * (1 << 125)
    r = round(f)
    assert abs(r) < (1 << 127)
    return r


def i128_hex(v):
    u = v & ((1 << 128) - 1)
    return "Q(0x%016XULL, 0x%016XULL)" % (u >> 64, u & ((1 << 64) - 1))


def big256(v):
    """Round a positive Decimal to a 256-bit significand W (top bit set) and exponent e,
    value = W * 2^(e-255)."""
    f = Fraction(v)
    assert f > 0
    e = 0
    while f >= 2 ** (e + 1):
        e += 1
    while f < 2 ** e:
        e -= 1
    W = round(f * Fraction(2) ** (255 - e))
    if W == 1 << 256:
        W >>= 1
        e += 1
    limbs = [(W >> (64 * i)) & ((1 << 64) - 1) for i in range(4)]
    return e, limbs


def big_init(v):
    e, l = big256(v)
    return "{{0x%016XULL, 0x%016XULL, 0x%016XULL, 0x%016XULL}, %d, false}" % (l[0], l[1], l[2], l[3], e)


def f128(v):
    """Positive Decimal to a normalized 128-bit significand m and exponent e, value = m*2^(e-127)."""
    f = Fraction(v)
    e = 0
    while f >= 2 ** (e + 1):
        e += 1
    while f < 2 ** e:
        e -= 1
    m = round(f * Fraction(2) ** (127 - e))
    if m == 1 << 128:
        m >>= 1
        e += 1
    return m, e


def dbl(fr):
    # Fraction -> nearest double literal (exact hex float).
    return float(fr).hex()


out = []
w = out.append
w("// Generated by macos/tests/x87-kernels/gen_tables.py: do not edit by hand.")
w("// Constants of X87Kernels.cpp. Q2.125 entries: signed 128-bit v = value * 2^125, rounded to")
w("// nearest. Big entries: 256-bit significand (limbs low to high), value = W * 2^(e - 255).")
w("#pragma once")
w("")
w("// clang-format off")
w("namespace faf_posix::x87::kernels_detail")
w("{")

# --- sin/cos table: j/64, j = 0..50 ------------------------------------------------------
w("  // sin(j/64), cos(j/64) for j = 0..50 (|r| <= pi66/4 < 50.27/64).")
w("  inline constexpr i128 kSinTable[51] = {")
for j in range(51):
    w("    %s," % i128_hex(q125(d_sin(Decimal(j) / 64))))
w("  };")
w("  inline constexpr i128 kCosTable[51] = {")
for j in range(51):
    w("    %s," % i128_hex(q125(d_cos(Decimal(j) / 64))))
w("  };")

# Polynomial coefficients.
def coef_list(name, fracs):
    w("  inline constexpr i128 %s[%d] = {" % (name, len(fracs)))
    for fr in fracs:
        with localcontext() as c:
            c.prec = PREC
            v = Decimal(fr.numerator) / Decimal(fr.denominator)
        w("    %s,  // %s" % (i128_hex(q125(v)), fr))
    w("  };")


def dbl_list(name, fracs):
    w("  inline constexpr double %s[%d] = {" % (name, len(fracs)))
    for fr in fracs:
        w("    %s,  // %s" % (dbl(fr), fr))
    w("  };")


# sin(d) = d * S(w), S(w) = sum_k (-w)^k / (2k+1)!
w("  // sin: S(w) = sum (-w)^k/(2k+1)!: fixed k = 0..3, double tail k = 4..6 (k = 7: < 2^-138).")
coef_list("kSinCoef", [Fraction(1, factorial(2 * k + 1)) for k in range(4)])
dbl_list("kSinTail", [Fraction(1, factorial(2 * k + 1)) for k in range(4, 7)])
w("  // cos: C(w) = sum (-w)^k/(2k)!: fixed k = 0..4, double tail k = 5..6 (k = 7: < 2^-134).")
coef_list("kCosCoef", [Fraction(1, factorial(2 * k)) for k in range(5)])
dbl_list("kCosTail", [Fraction(1, factorial(2 * k)) for k in range(5, 7)])
w("  // atan: Q(w) = sum (-w)^k/(2k+1): fixed k = 0..5, double tail k = 6..8 (k = 9: < 2^-130).")
coef_list("kAtanCoef", [Fraction(1, 2 * k + 1) for k in range(6)])
dbl_list("kAtanTail", [Fraction(1, 2 * k + 1) for k in range(6, 9)])
w("  // log: P(t) = sum (-t)^n/(n+1) (ln(1+t) = t*P(t)): fixed n = 0..9, double tail n = 10..15")
w("  // (n = 16: < 2^-132).")
coef_list("kLogCoef", [Fraction(1, n + 1) for n in range(10)])
dbl_list("kLogTail", [Fraction(1, n + 1) for n in range(10, 16)])
w("  // expm1: E(g) = sum g^n/(n+1)! (expm1(g) = g*E(g)): fixed n = 0..7, double tail n = 8..12")
w("  // (n = 13: < 2^-134).")
coef_list("kExpCoef", [Fraction(1, factorial(n + 1)) for n in range(8)])
dbl_list("kExpTail", [Fraction(1, factorial(n + 1)) for n in range(8, 13)])

# atan table j/64, j = 0..64
w("  // atan(j/64), j = 0..64.")
w("  inline constexpr i128 kAtanTable[65] = {")
for j in range(65):
    w("    %s," % i128_hex(q125(d_atan(Decimal(j) / 64))))
w("  };")

# log table: idx = 8 significand bits after the leading one; inv = INV/2^24 ~ 1/c,
# c = 1 + (idx + 0.5)/256. Entries 0 and 255 are not used (special-cased: inv 1 and 1/2).
w("  // log2: for idx = 1..254 (the 8 bits after the leading one of the significand),")
w("  // inv = kLogInv[idx] * 2^-24 ~ 1/(1 + (idx + 0.5)/256), kLogMinusLog2Inv[idx] = -log2(inv).")
w("  // t = m*inv - 1 is exact; |t| <= kLogTMax (checked by the generator). Entries 0 and 255 unused.")
invs = []
maxt = Fraction(0)
for idx in range(256):
    if idx in (0, 255):
        invs.append(0)
        continue
    c = Fraction(512 + 2 * idx + 1, 512)
    INV = round(Fraction(1 << 24) / c)
    invs.append(INV)
    lo = Fraction(256 + idx, 256)
    hi = Fraction(256 + idx + 1, 256)
    for m in (lo, hi):
        t = abs(m * Fraction(INV, 1 << 24) - 1)
        maxt = max(maxt, t)
assert maxt <= Fraction(1, 512) + Fraction(1, 1 << 22), float(maxt)
w("  inline constexpr std::uint32_t kLogInv[256] = {")
for i in range(0, 256, 8):
    w("    " + ", ".join("%du" % v for v in invs[i:i + 8]) + ",")
w("  };")
w("  inline constexpr i128 kLogMinusLog2Inv[256] = {")
for idx in range(256):
    if invs[idx] == 0:
        w("    Q(0, 0),")
        continue
    with localcontext() as cx:
        cx.prec = PREC
        v = (Decimal(1 << 24) / Decimal(invs[idx])).ln() / LN2
    w("    %s," % i128_hex(q125(v)))
w("  };")
w("  // max |t| over idx 1..254 = %.6g (2^-9 = %.6g)" % (float(maxt), 2.0 ** -9))

# exp2 table 2^(j/64), j = -64..64
w("  // 2^(j/64) for j = -64..64 (index j + 64).")
w("  inline constexpr i128 kExp2Table[129] = {")
for j in range(-64, 65):
    with localcontext() as cx:
        cx.prec = PREC
        v = (LN2 * j / 64).exp()
    w("    %s," % i128_hex(q125(v)))
w("  };")

# RN64 constants for FPATAN's special values (pi, pi/2, pi/4 share kPi's significand).
def rn64_ext(v):
    f = Fraction(v)
    e = 0
    while f >= 2 ** (e + 1):
        e += 1
    while f < 2 ** e:
        e -= 1
    m = round(f * Fraction(2) ** (63 - e))
    if m == 1 << 64:
        m >>= 1
        e += 1
    return m, e + 16383


m, se = rn64_ext(PI)
assert (m, se) == (0xC90FDAA22168C235, 0x4000)
m, se = rn64_ext(3 * PI / 4)
w("  inline constexpr Ext kExt3PiOver4{0x%016XULL, 0x%04X};  // RN64(3*pi/4)" % (m, se))

# Scalar Q2.125 constants
w("  inline constexpr i128 kPiQ = %s;" % i128_hex(q125(PI)))
w("  inline constexpr i128 kPiOver2Q = %s;" % i128_hex(q125(PI / 2)))
w("  inline constexpr i128 kLn2Q = %s;" % i128_hex(q125(LN2)))
w("  inline constexpr i128 kLog2eQ = %s;" % i128_hex(q125(LOG2E)))

# F128 constants
for name, v in (("kLn2F", LN2), ("kLog2eF", LOG2E)):
    m, e = f128(v)
    w("  inline constexpr u128 %sM = (u128(0x%016XULL) << 64) | 0x%016XULL;  // exponent %d"
      % (name, m >> 64, m & ((1 << 64) - 1), e))
    w("  inline constexpr int %sE = %d;" % (name, e))

# Reduction constants: Cp = pi66/2 in units of 2^-65, INV = floor(2^190 / Cp)
pi66_68 = 0xC90FDAA22168C234C
assert pi66_68 & 3 == 0
Cp = pi66_68 >> 2      # pi66 = Cp * 2^-64 ; pi66/2 = Cp * 2^-65
assert Cp.bit_length() == 66
# pi66 must be the truncation of true pi at 66 bits... check against PI
assert abs(Fraction(Cp, 1 << 64) - Fraction(PI)) < Fraction(1, 1 << 64)
INV = (1 << 190) // Cp
w("  // Intel's 66-bit pi: pi66 = kPi66Units * 2^-64, so pi66/2 = kPi66Units * 2^-65.")
w("  inline constexpr u128 kPi66Units = (u128(0x%XULL) << 64) | 0x%016XULL;" % (Cp >> 64, Cp & ((1 << 64) - 1)))
w("  inline constexpr u128 kPi66Recip190 = (u128(0x%016XULL) << 64) | 0x%016XULL;  // floor(2^190 / kPi66Units)"
  % (INV >> 64, INV & ((1 << 64) - 1)))

# Slow-path constants
w("  // Slow path (256-bit significands).")
w("  inline constexpr BigConst kBigLn2 = %s;" % big_init(LN2))
w("  inline constexpr BigConst kBigLog2e = %s;" % big_init(LOG2E))
w("  inline constexpr BigConst kBigPi = %s;" % big_init(PI))
w("  inline constexpr BigConst kBigPiOver2 = %s;" % big_init(PI / 2))
w("  // atan(k/16), k = 1..16 (index k).")
w("  inline constexpr BigConst kBigAtan16[17] = {")
w("    {{0, 0, 0, 0}, 0, true},")
for k in range(1, 17):
    w("    %s," % big_init(d_atan(Decimal(k) / 16)))
w("  };")

w("} // namespace faf_posix::x87::kernels_detail")
w("// clang-format on")

dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
    "src", "platform", "posix", "math", "X87KernelsTables.h")
with open(dst, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.normpath(dst), "max|t| =", float(maxt))
